-- 014. 사업 유형 — LXP 를 학내형/개방형으로 가른다
--
--   mysql -u root --default-character-set=utf8mb4 iworks_local     < studio/sql/014_migration_project_track.sql
--   mysql -u root --default-character-set=utf8mb4 blueassign_test  < studio/sql/014_migration_project_track.sql
--
-- LXP 는 셋으로 갈린다. 학교 구성원만 쓰는 학내형, 외부에 열어 두는
-- 개방형, 둘을 겸하는 하이브리드. 범위도 인증 방식도 달라서 한 덩어리로
-- 두면 과업 성격이 가려진다.
--
-- 'lxp' 는 LXP 가 하나뿐일 때 붙인 코드다. 이제 그 값이 가리키는 것은
-- 학내형뿐이므로 'lxp_campus' 로 바꾼다. **값이 거의 없는 지금이 가장 싸다.**
-- 쌓인 뒤에는 "lxp 가 학내형인가 전체인가" 를 영영 되물어야 한다.
--
-- 'lxp_open'(개방형)은 새 값이라 적재할 것이 없다. 화면에만 더하면 된다.
--
-- track 은 VARCHAR 이고 CHECK 도 ENUM 도 없다. 코드는 화면이 표에서 찾고,
-- 못 찾으면 코드를 그대로 보여 준다(BS_PROJECT_TRACK[$t] ?? $t). 그래서
-- 이 치환이 늦어도 화면이 깨지지는 않는다 — 'lxp' 라고 보일 뿐이다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. 쌓인 값 치환
--
-- 다시 돌려도 안전하다. 두 번째에는 바꿀 행이 없다.
-- ---------------------------------------------------------------------
UPDATE `bs_project` SET `track` = 'lxp_campus' WHERE `track` = 'lxp';


-- ---------------------------------------------------------------------
-- 2. 컬럼 주석
--
-- 허용값을 주석으로만 적어 둔 방식이다(ENUM 대신 VARCHAR+COMMENT —
-- docs/conventions.md). 주석이 낡으면 DB 만 보는 사람이 틀린 목록을 믿는다.
-- ---------------------------------------------------------------------
ALTER TABLE `bs_project`
  MODIFY COLUMN `track` VARCHAR(40) NULL
  COMMENT '사업 유형. lms_b2b|lxp_campus|lxp_open|lxp_hybrid|용역|사내';


