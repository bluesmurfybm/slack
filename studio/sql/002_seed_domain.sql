-- · 쉼표로 구분, 쉼표 뒤 공백 없음 (수집기가 explode(',') 로 자른다)
-- · 한국어 위주. 실무에서 슬랙·메일 제목에 실제로 쓰이는 말을 넣는다
-- · 영문 약어는 현장에서 한글보다 자주 쓰이는 것만 (SSO, API, IBT, SMS …)
-- · 너무 일반적인 낱말(오류, 수정, 확인, 요청, 문의)은 넣지 않는다.
--   모든 분야에 걸려 변별력이 사라진다
