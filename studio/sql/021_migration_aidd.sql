-- ┌──────────────────────────────────────────────────────────────────┐
-- │ 왜 프로젝트에 붙는가                                              │
-- │                                                                  │
-- │ AIDD 보정은 **두 단계에 걸쳐** 작동한다 —                         │
-- │   3단계(WBS) 공수 산정 · 4단계 배정의 가용도                      │
-- │                                                                  │
-- │ bs_allocation.params_json 에만 두면 3단계가 못 본다. 그래서       │
-- │ 프로젝트를 원본으로 두고, 배정안은 산출 시점 값을 params_json 에  │
-- │ **복사해 기록**한다(재현용). 차수마다 끌 수도 있다.               │
-- └──────────────────────────────────────────────────────────────────┘
--
-- ┌──────────────────────────────────────────────────────────────────┐
-- │ 계수는 지어낸 값이다 — 그래서 칸에 담아 드러낸다                  │
-- │                                                                  │
-- │ 우리 회사의 AIDD 속도 향상 실측이 없다. scoring-design.md 가      │
-- │ "사람이 자의로 정하는 것보다 데이터에서 뽑는 것이 방어하기 쉽다"  │
-- │ 며 계열 기준값을 90분위로 뽑아 둔 것과 어긋나는 자리다.           │
-- │                                                                  │
-- │ 그러니 상수로 코드에 묻지 않는다. 프로젝트마다 적어 두고, 화면에  │
-- │ 보여 주고, 배정안에 박제한다. 나중에 실적이 쌓이면 이 칸의 값과   │
-- │ 실제를 견줄 수 있다.                                              │
-- └──────────────────────────────────────────────────────────────────┘
--
-- 기본값은 보수적으로 잡았다 — 요청이 "조금이라도 고려" 였다.
--   aidd_effort 0.85  공수 15% 단축
--   aidd_load   0.95  타 업무 점유 5% 할인
--
-- 난이도(difficulty)는 **건드리지 않는다.** 난이도는 공수 환산 말고도
-- ★4+ 상위자 게이트·추정 점유·실적의 재료로 쓰인다. 낮추면 어려운 일이
-- 못 하는 사람에게 가고, 그 값이 실적으로 남아 영구히 오염된다.
-- AI 는 타이핑과 뼈대를 빠르게 하지 어려운 문제를 쉽게 만들지 않는다.
-- =====================================================================

ALTER TABLE `bs_project`
  ADD COLUMN `aidd_enabled` TINYINT(1) NOT NULL DEFAULT 1
      COMMENT 'AIDD 고려 옵션. 1=켬(기본). 끄면 공수·가용도 보정이 전부 멈춘다'
      AFTER `deploy_date`,
  ADD COLUMN `aidd_effort` DECIMAL(3,2) NOT NULL DEFAULT 0.85
      COMMENT '공수 계수. 난이도 환산값에 곱한다. 0.85 = 15% 단축. 1.00 이면 보정 없음'
      AFTER `aidd_enabled`,
  ADD COLUMN `aidd_load` DECIMAL(3,2) NOT NULL DEFAULT 0.95
      COMMENT '타 업무 점유 반영률. 0.95 = 점유를 5% 할인해 그만큼 여유로 본다'
      AFTER `aidd_effort`;


-- ---------------------------------------------------------------------
-- 이미 있는 프로젝트도 기본값을 받는다.
--
-- DEFAULT 는 새로 넣는 줄에만 걸리므로 NOT NULL 로 만들면서 기존 줄은
-- 0 이 아니라 DEFAULT 로 채워진다(MySQL 동작). 그래도 **눈으로 확인한다** —
-- 0.00 이 들어가면 공수가 전부 0 이 되는 자리다.
-- ---------------------------------------------------------------------
UPDATE `bs_project`
   SET `aidd_effort` = 0.85
 WHERE `aidd_effort` IS NULL OR `aidd_effort` <= 0;

UPDATE `bs_project`
   SET `aidd_load` = 0.95
 WHERE `aidd_load` IS NULL OR `aidd_load` <= 0;


